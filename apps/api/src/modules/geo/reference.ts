export function slugFromSysname(sysname: string): string {
  return sysname.startsWith(CULTURE_SYSNAME_PREFIX) ? sysname.slice(CULTURE_SYSNAME_PREFIX.length) : sysname;
}

export function baName(ru: string): string {
  if (BA_CITY[ru]) return BA_CITY[ru];
  const m = ru.match(/^(\S+)\s+район$/);
  if (m?.[1] && BA_DISTRICT_STEM[m[1]]) return `${BA_DISTRICT_STEM[m[1]]} районы`;
  return ru;
}

export function kindOf(ru: string): "city" | "district" {
  return ru.endsWith(" район") ? "district" : "city";
}

/** Основы для поиска названия в тексте с учётом падежей: «в Уфе», «Стерлитамаке», «в Баймакском районе». */
export function stemsFor(ru: string): string[] {
  const base = ru
    .replace(/ район$/, "")
    .toLowerCase()
    .replaceAll("ё", "е");
  const stems = new Set<string>();
  if (ru.endsWith(" район")) {
    stems.add(base.replace(/(ский|цкий|ий|ый)$/, ""));
  } else {
    if (/[аяыиоуеьй]$/.test(base)) stems.add(base.slice(0, -1));
    else stems.add(base);
    if (base.endsWith("ий")) stems.add(base.slice(0, -2));
  }
  stems.add(base);
  return [...stems].filter((s) => s.length >= 2).sort();
}
